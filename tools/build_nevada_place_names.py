"""Write game/scripts/content/nevada_place_names.gd from the USGS GNIS file.

The names are every Nevada feature that GNIS classes as a Populated Place,
current or historical, plus every Census Designated Place. GNIS is a work of
the United States Government and is in the public domain. Download the Nevada
text file from the USGS National Map and pass the extracted `.txt`:

    https://prd-tnm.s3.amazonaws.com/StagedProducts/GeographicNames/DomesticNames/DomesticNames_NV_Text.zip

    python3 tools/build_nevada_place_names.py DomesticNames_NV.txt
"""

from __future__ import annotations

import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "game" / "scripts" / "content" / "nevada_place_names.gd"
# The new-city dialog's name field holds this many characters.
MAX_LENGTH = 24
CDP_SUFFIX = re.compile(r" Census Designated Place$")
HISTORICAL = re.compile(r" \(historical\)$")


def read_names(path: Path) -> list[str]:
    names: set[str] = set()
    with path.open(encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f, delimiter="|"):
            if row["state_name"] != "Nevada":
                continue
            name = HISTORICAL.sub("", row["feature_name"].strip())
            if row["feature_class"] == "Census":
                if not CDP_SUFFIX.search(name):
                    continue
                name = CDP_SUFFIX.sub("", name)
            elif row["feature_class"] != "Populated Place":
                continue
            if 2 < len(name) <= MAX_LENGTH:
                names.add(name)
    return sorted(names, key=lambda n: (n.casefold(), n))


def render(names: list[str]) -> str:
    lines = [
        "# SPDX-FileCopyrightText: 2026 Bristlecone Artists LLC",
        "# SPDX-License-Identifier: GPL-3.0-or-later",
        "# See LICENSE and LICENSING.md in the repository root.",
        "",
        "## Real Nevada town names: every GNIS Populated Place in Nevada, current",
        "## or historical, and every Census Designated Place. GNIS is public domain.",
        "## Generated by tools/build_nevada_place_names.py; do not edit by hand.",
        "class_name NevadaPlaceNames",
        "extends RefCounted",
        "",
        "const NAMES: Array[String] = [",
    ]
    row: list[str] = []
    width = 1
    for name in names:
        item = '"%s",' % name.replace("\\", "\\\\").replace('"', '\\"')
        if row and width + len(item) + 1 > 88:
            lines.append("\t" + " ".join(row))
            row, width = [], 1
        row.append(item)
        width += len(item) + 1
    if row:
        lines.append("\t" + " ".join(row))
    lines.append("]")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("gnis", type=Path, help="extracted DomesticNames_NV.txt")
    args = parser.parse_args()
    names = read_names(args.gnis)
    OUT.write_text(render(names), encoding="utf-8")
    print(f"wrote {len(names)} names to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
